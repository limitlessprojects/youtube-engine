#!/usr/bin/env python3
"""rejected_log.py — failure-mode ledger fed by the gate (research/video-notes/rejected/).

Walks content/<slug>/gate/ultracritic_r*.json (frame-wise 5-dim grades) + probe/vlm_gate reports,
extracts every below-threshold frame (dim < THRESH_DIM=7.0 or frame-mean < 6.0 floor), and writes a
timestamped markdown ledger grouped by failure class. No frames/binary assets committed — records only.

Usage:
  python3 tools/rejected_log.py <slug>                 # writes rejected/<slug>-<ts>.md
  python3 tools/rejected_log.py <slug> --print          # stdout instead
Output: research/video-notes/rejected/<slug>-<ts>.md (or stdout).
"""
import json
import os
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
THRESH_DIM = 7.0
FLOOR = 6.0
OUT = REPO / "research" / "video-notes" / "rejected"


def load_rounds(gate: Path) -> list[tuple[str, dict]]:
    rounds = []
    for p in sorted(gate.glob("ultracritic_r*.json")):
        try:
            rounds.append((p.stem, json.loads(p.read_text())))
        except Exception:
            continue
    vr = gate / "report.json"
    if vr.exists():
        try:
            rounds.append(("vlm_gate", json.loads(vr.read_text())))
        except Exception:
            pass
    return rounds


def frames_failing(r: dict) -> list[tuple[str, dict]]:
    """ultracritic frame records: candidates dict keys with scores dict."""
    out = []
    fl = r.get("frames", [])
    if isinstance(fl, list):
        for r_item in fl:
            if not isinstance(r_item, dict):
                continue
            fr = r_item.get("frame") or r_item.get("key") or r_item.get("name")
            scores = r_item.get("scores") or r_item.get("dims") or {}
            if not isinstance(scores, dict):
                continue
            low = {k: v for k, v in scores.items() if isinstance(v, (int, float)) and v < THRESH_DIM}
            mean = sum(v for v in scores.values() if isinstance(v, (int, float))) / max(1, len(scores))
            if low or mean < FLOOR:
                out.append((fr, {"low_dims": low, "mean": round(mean, 2)}))
    # vlm_gate format: {"frames": {sid: {...verdict...}}}
    if "frames" in r and isinstance(r["frames"], dict):
        for sid, det in r["frames"].items():
            if isinstance(det, dict) and str(det.get("verdict", "")).lower() == "fix":
                det = {k: det[k] for k in ("verdict", "issues") if k in det}
                out.append((sid, {"vlm_verdict": "fix", "detail": det}))
    return out


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    slug = sys.argv[1]
    printing = "--print" in sys.argv
    gate = REPO / "content" / slug / "gate"
    if not gate.exists():
        print(f"no gate dir: {gate}", file=sys.stderr)
        return 2
    rounds = load_rounds(gate)
    OUT.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    lines = [f"# Rejected-log — {slug} — {stamp}",
             "",
             "Auto-generated by tools/rejected_log.py from gate/ultracritic_r*.json + gate/report.json.",
             f"Thresholds: any dim < {THRESH_DIM} or frame-mean < {FLOOR}.",
             ""]
    any_hits = False
    for name, r in rounds:
        hits = frames_failing(r)
        if not hits:
            lines += [f"## {name} — clean (nothing below threshold)", ""]
            continue
        any_hits = True
        lines += [f"## {name} — {len(hits)} below-threshold frame(s)"]
        for fr, d in hits:
            lines.append(f"- `{fr}` — {json.dumps(d)[:400]}")
        lines.append("")
    if not any_hits:
        lines += ["_No gate failures recorded on this run._"]
    body = "\n".join(lines) + "\n"
    if printing:
        print(body)
        return 0
    out_path = OUT / f"{slug}-{stamp}.md"
    out_path.write_text(body, encoding="utf-8")
    print(f"wrote {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
